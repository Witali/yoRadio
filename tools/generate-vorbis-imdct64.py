"""Extract unchanged Xiph backward-transform bodies; never modify the baseline."""
import argparse, hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
UPSTREAM = ROOT / 'idf/components/native_vorbis_xiph/upstream/libvorbis'
TARGET = ROOT / 'idf/components/native_vorbis_transform'
SOURCE_SHA = 'e32b379d7a3d9253524abae3c41c5ac2486bf166cf65996efc4e68db1b164993'


def generated_body(source):
    if hashlib.sha256(source).hexdigest() != SOURCE_SHA:
        raise ValueError('pinned Xiph MDCT source identity changed')
    start = source.index(b'STIN void mdct_butterfly_8(')
    clear = source.index(b'void mdct_clear(')
    reverse = source.index(b'STIN void mdct_bitreverse(')
    forward = source.index(b'void mdct_forward(')
    banner = source[:source.index(b' function:')]
    # Keep each complete function body, comments and whitespace byte-for-byte.
    return (b'// Generated by tools/generate-vorbis-imdct64.py; do not edit.\n' +
        b'// Types/constants and lookup ownership are supplied by transform.c.\n' +
        banner + b' Unchanged Xiph inverse-transform function bodies.\n\n ********************************************************************/\n\n' +
        source[start:clear] + b'\n' + source[reverse:forward])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    body = generated_body((UPSTREAM / 'lib/mdct.c').read_bytes())
    outputs = {'xiph_backward.inc':body, 'COPYING':(UPSTREAM / 'COPYING').read_bytes()}
    if args.check:
        if not all((TARGET / name).read_bytes() == value for name, value in outputs.items()):
            raise ValueError('generated transform bodies/license do not match pinned Xiph')
    else:
        TARGET.mkdir(parents=True,exist_ok=True)
        for name, value in outputs.items():
            (TARGET / name).write_bytes(value)
    print('Xiph backward-transform bodies and license match the pinned source.')


if __name__ == '__main__':
    main()
