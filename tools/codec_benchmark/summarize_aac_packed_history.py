#!/usr/bin/env python3
"""Regenerate compact tables from retained, validated packed-history runs."""
import argparse
import json
import math
from pathlib import Path

import run_aac_packed_history as experiment

ROOT = Path(__file__).resolve().parents[2]
NAMES = ("synthetic", "groovesalad64", "groovesalad32", "groovesalad16", "abba64", "groovesalad128")


def report(directory):
    results = {}
    for name in NAMES:
        path = directory / name
        saved = json.loads((path / "result.json").read_text())
        parsed = experiment.parse_log((path / "qemu.log").read_text())
        if any(saved[key] != value for key, value in parsed.items()):
            raise ValueError(f"Saved result differs from log: {name}")
        results[name] = saved
    rows = []
    for name in ("synthetic", "groovesalad16", "abba64"):
        for s in results[name]["summaries"]:
            if s["variant"] not in range(1, 7) or (name == "synthetic" and not s["case"].startswith("hev2")):
                continue
            channels = [r for r in results[name].get("error_statistics", [])
                        if r["variant"] == s["variant"] and r["run"] == 1]
            rows.append(dict(recording=name, **s,
                             over_two_percent=100 * s["over_two_per_run"][0] / s["samples_per_run"],
                             rms_lsb=[r["derived"]["rms_error_lsb"] for r in channels]))
    # Conditional inference from the supplied table, not a reproduced FAAD run.
    source_rms = 8.209e-8 * 10 ** (100.626 / 20)
    source_error_pcm = math.sqrt(234 / 274432)
    comparison = {"assumption": "Supplied SNR uses 20*log10(signal_RMS/error_RMS); counts describe the same signal",
                  "supplied_inferred_signal_rms_fs": source_rms,
                  "supplied_inferred_signal_dbfs": 20 * math.log10(source_rms),
                  "supplied_16bit_error_rms_lsb": source_error_pcm,
                  "supplied_inferred_16bit_snr_db": 20 * math.log10(source_rms * 32768 / source_error_pcm),
                  "supplied_pre_pcm_peak_error_lsb": 1.393e-6 * 32768}
    summary = {"precision_limit_lsb": 5, "production_precision_limit_lsb": 2,
               "production_qualified": False, "ram_saved_bytes": 0,
               "paired_comparisons": sum(len(r["runs"]) for r in results.values()),
               "rows": rows, "supplied_study_comparison": comparison}
    lines = ["# Packed complex history: retained measurements", "",
             "Generated by `tools/codec_benchmark/summarize_aac_packed_history.py`.", "",
             "PCM limits: temporary development ±5 LSB, final production ±2 LSB per channel/sample.",
             "Counts below use one run;",
             "all three runs reproduce the same PCM differences. Instruction overhead is",
             "the median of runs 2/3, including wrapper checks/counters, not hardware CPU load.", "",
             "| Input | Variant | Coverage | Max LSB | >5 LSB count | >2 LSB count | >2 LSB % | RMS L/R, LSB | Extra instructions |",
             "| --- | --- | --- | ---: | ---: | ---: | ---: | --- | ---: |"]
    for r in rows:
        rms = "/".join(f"{v:.4f}" for v in r["rms_lsb"]) or "not collected"
        lines.append(f"| {r['recording']} | {r['name']} | {r['coverage']} | {r['max_pcm_error_lsb']} | "
                     f"{r['over_limit_per_run'][0]:,} | {r['over_two_per_run'][0]:,} | {r['over_two_percent']:.6f} | {rms} | "
                     f"{r['instruction_overhead_median_percent']:+.3f}% |")
    lines += ["", "The HE-AAC v1 Groove Salad 32/64 kbps and AAC-LC 128 kbps recordings are",
              "bit-identical controls with no active packed complex history. Groove Salad",
              "16 kbps exercises complex SBR but not the wrapped PS path; its PS-only zero",
              "errors are not evidence of PS quantizer accuracy. ABBA exercises SBR and PS.", "",
              "Original BFP16 regression: 45 additional comparisons, with unchanged PCM",
              "relative to the saved 2026-09-30 experiment. It retains its historical one-LSB gate.", "",
              "## Conditional comparison with the supplied FAAD2 study", "",
              f"Using the study's SNR and error RMS gives an inferred signal level of {comparison['supplied_inferred_signal_dbfs']:.2f} dBFS.",
              f"Its 234 / 274,432 one-LSB differences give {source_error_pcm:.5f} LSB RMS after int16 rounding.",
              f"For that inferred signal level the corresponding int16 SNR would be {comparison['supplied_inferred_16bit_snr_db']:.2f} dB,",
              "rather than the table's 100.626 dB. This indicates different measurement",
              "stages, assuming the SNR formula and signal normalization are conventional.",
              "The original source, build settings and recording are needed to establish",
              "the exact reason. This calculation is not a rerun of that experiment.", ""]
    return summary, "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results", type=Path,
                        default=ROOT / "tests/results/esp32c3-aac-packed-history-20261001")
    args = parser.parse_args()
    summary, markdown = report(args.results)
    (args.results / "summary.json").write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8", newline="\n")
    (args.results / "TABLES.md").write_text(markdown, encoding="utf-8", newline="\n")
