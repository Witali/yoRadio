"""Generate Q19 Blackman-windowed sinc tables for the C3 integer PDM clock."""
import argparse
from pathlib import Path
from compare_integer_rate_filters import weights

TAPS = 32
BITS = 19


def table(phases, endpoint):
    result=[]
    for phase in range(phases+int(endpoint)):
        values=weights(TAPS,phase/phases)
        q=[round(v*(1<<BITS)) for v in values]
        peak=max(range(TAPS),key=lambda k:abs(values[k]))
        q[peak]+=(1<<BITS)-sum(q)
        assert sum(q)==1<<BITS
        result.append(q)
    return result


def generate():
    lines=['// Generated by tools/codec_benchmark/generate_pcm_fir.py; do not edit.',
           '// Q19, 32 taps, exact DC sum. Constant tables remain in Flash.',
           '#pragma once', '#include <stdint.h>']
    for name,phases,endpoint in [('pcm_fir_coefficients',256,True),('pcm_fir_48k_coefficients',625,False)]:
        rows=table(phases,endpoint)
        lines.append(f'static const int32_t {name}[{len(rows)}][{TAPS}] = {{')
        lines.extend('    {'+', '.join(map(str,row))+'},' for row in rows)
        lines.append('};')
    return '\n'.join(lines)+'\n'


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output',type=Path,required=True)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    text=generate()
    if args.check:
        assert args.output.read_text()==text,'Coefficient table differs'
    else:
        args.output.write_text(text)
