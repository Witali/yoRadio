"""Build-local, optional GHASH acceleration for the audited ESP-IDF AES port."""
import argparse
import hashlib
from pathlib import Path

SOURCE_SHA256 = '9945ad8f72e401410d634ce7d2ab5d261681c9b5eaf1ddf4bb5329c52095749b'
HEADER_SHA256 = '7b37b91a0937668f461c3caca92d13c29666fd346ff52f8faf71daf252fc67f4'

def normalize(data):
    return data.decode().replace('\r\n','\n')

def reduction8():
    values = []
    for byte in range(256):
        value = byte
        for _ in range(8):
            value = (value >> 1) ^ ((0xe1 << 120) if value & 1 else 0)
        assert value & ((1 << 96)-1) == 0
        values.append(value >> 96)
    rows = [', '.join(f'0x{x:08x}U' for x in values[i:i+8])+',' for i in range(0,256,8)]
    return ('/* NIST SP 800-38D polynomial reduction, generated by patch_gcm_byte_ghash.py. */\n'
            'static const uint32_t yoradio_gcm_reduction8[YORADIO_GHASH_BYTE_VALUES] = {\n    '+
            '\n    '.join(rows)+'\n};\n').encode()

def patch(source, header):
    text = normalize(source)
    if hashlib.sha256(text.encode()).hexdigest() != SOURCE_SHA256:
        raise ValueError('Unaudited AES-GCM source; recheck all GHASH callers')
    if hashlib.sha256(normalize(header).encode()).hexdigest() != HEADER_SHA256:
        raise ValueError('Unaudited AES-GCM context layout')
    marker = '/* Update the key value in gcm context */'
    assert text.count(marker)==1
    text = text.replace(marker, '#include "gcm_byte_ghash.inc"\n\n'+marker)
    marker = 'static void esp_gcm_ghash(esp_gcm_context *ctx, const unsigned char *x, size_t x_len, uint8_t *z)\n{'
    assert text.count(marker)==1
    text = text.replace(marker, marker+'\n    if (x_len >= YORADIO_GHASH_LARGE_MIN_BYTES) {\n'
        '        yoradio_gcm_ghash_large(ctx, x, x_len, z);\n        return;\n    }\n')
    return text.encode()

def write(path, data):
    path.parent.mkdir(parents=True,exist_ok=True)
    if not path.exists() or path.read_bytes()!=data:
        path.write_bytes(data)

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--input',type=Path,required=True)
    p.add_argument('--header',type=Path,required=True)
    p.add_argument('--output',type=Path,required=True)
    args=p.parse_args()
    write(args.output,patch(args.input.read_bytes(),args.header.read_bytes()))
    write(args.output.with_name('gcm_reduction8.inc'),reduction8())
