def module_from_path(name, path, expected):
    need(sha(path.read_bytes()) == expected, 'Unreviewed offline module source')
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def verify(bundle, repository):
    bundle, repository = bundle.resolve(), repository.resolve()
    manifest = obj((bundle / 'manifest.json').read_bytes())
    need(manifest['schema'] == 'c3-map2-checkpoint-v1' and set(manifest['plan']['roles']) == {'baseline', 'acceptance', 'numeric'},
         'Unknown focused C3 checkpoint')
    need(manifest['dependency_archive'] == dict(path='tests/results/cyd-vorbis-map2-20261020',
        manifest_sha256=MANIFEST_SHA, required=True, standalone=False), 'Explicit committed dependency required')
    dep = Dependency(repository)
    # Reuse the exact already-reviewed verifier for the committed dependency;
    # this checks the actual historical NONPASS and independent Xiph provenance.
    dependency_verifier = module_from_path('pinned_committed_cyd_checkpoint_verify', dep.root / 'verify.py', VERIFY_SHA)
    need(dependency_verifier.verify(dep.root)['verified'] is True, 'Committed CYD dependency failed its reviewed verifier')
    files, raw, stored = manifest['files'], {}, {'manifest.json'}
    for original, row in files.items():
        rel(original)
        need(type(row['raw_bytes']) is int and row['raw_bytes'] >= 0 and
             re.fullmatch('[0-9a-f]{64}', row['raw_sha256']), 'Invalid raw identity')
        if 'dependency_key' in row:
            need(row['stored'] is None and row['dependency_key'] == original, 'Only exact original-path dependency keys supported')
            data = dep.read(row['dependency_key'])
        elif row['stored'] is None:
            need(row.get('omitted'), 'Undeclared binary omission')
            if 'actual_elf_header64_hex' in row:
                header = bytes.fromhex(row['actual_elf_header64_hex'])
                need(len(header) == 64 and header[:6] == b'\x7fELF\x01\x01' and
                     struct.unpack_from('<H', header, 18)[0] == 243, 'Actual RV32 ELF64 metadata required')
            continue
        else:
            path = (bundle / rel(row['stored'])).resolve()
            need(path.is_relative_to(bundle) and row['stored'] not in stored, 'Unsafe/duplicate stored file')
            stored.add(row['stored'])
            blob = path.read_bytes()
            need(len(blob) == row['stored_bytes'] and sha(blob) == row['stored_sha256'], 'Stored bytes differ')
            need(row['encoding'] in ('raw', 'gzip'), 'Unknown stored encoding')
            data = gzip.decompress(blob) if row['encoding'] == 'gzip' else blob
            if original.endswith(('.py', '.h')):
                need(row['encoding'] == 'raw', 'Source must remain uncompressed')
        need(len(data) == row['raw_bytes'] and sha(data) == row['raw_sha256'], 'Decoded/dependency identity differs')
        raw[original] = data
    for name, row in manifest['generated'].items():
        path = (bundle / rel(name)).resolve()
        need(path.is_relative_to(bundle) and name not in stored, 'Unsafe generated file')
        stored.add(name)
        need(len(path.read_bytes()) == row['bytes'] and sha(path.read_bytes()) == row['sha256'], 'Generated bytes differ')
    need((bundle / '.gitattributes').read_bytes() == b'* -text whitespace=cr-at-eol,-blank-at-eof,-blank-at-eol,-space-before-tab\n',
         'Raw Git byte policy missing')
    need({p.relative_to(bundle).as_posix() for p in bundle.rglob('*') if p.is_file()} == stored, 'Stored inventory differs')
    base = manifest['repository'].rstrip('/')

    def original(role, path):
        name = norm(path)
        if name in manifest['aliases'].get(role, {}):
            return manifest['aliases'][role][name]
        need(name.startswith(base + '/'), 'Original path outside checkpoint repository')
        return rel(name[len(base) + 1:])

    def key(role, relative): return manifest['roles'][role]['root'] + '/' + rel(relative)
    def data(role, relative): return raw[key(role, relative)]
    def record(role, relative='report.json'): return obj(data(role, relative))
    def identity(role, relative): return files[key(role, relative)]['raw_sha256']
    reports = {role: record(role) for role in manifest['roles']}

    for role in ('baseline', 'acceptance', 'numeric'):
        report, selection = reports[role], manifest['plan']['roles'][role]
        need(identity(role, 'report.json') == selection['report_sha256'], 'Root-reviewed actual report identity differs')
        need(all(report.get(flag) is not True for flag in ('passed', 'numeric_reference_qualified', 'format_corpus_qualified',
             'full_G6_qualified', 'physical_device', 'production_radio_integration')), 'Checkpoint scope inflated')
        terminal = obj(raw[manifest['roles'][role]['terminal']])
        actual_exit = terminal.get('exit_code', terminal.get('returncode'))
        need(type(actual_exit) is int and actual_exit == selection['expected_outer_exit'], 'Actual terminal exit differs')
        need(terminal.get('schema') == 'direct-exec-tool-terminal-v1' or terminal.get('status') == 'TERMINAL', 'Actual terminal required')
        if 'report_sha256' in terminal:
            need(terminal['report_sha256'] == selection['report_sha256'] and terminal['entrypoint_sha256'] == RUNNER and
                 type(terminal['session_id']) is int and terminal['session_id'] > 0 and terminal['terminal_chunk_id'], 'Direct-tool report/source/session binding')
        for path, row in terminal.get('logs', {}).items():
            need(files[original(role, path)]['raw_sha256'] == row['sha256'], 'Actual outer log identity differs')
        for path, row in report.get('inputs', {}).items():
            archived = original(role, path if 'snapshot' in row else row['path'])
            need(files[archived]['raw_sha256'] == row['sha256'] and
                 ('bytes' not in row or files[archived]['raw_bytes'] == row['bytes']), 'Frozen input identity differs')
            if 'snapshot' in row:
                need(archived == key(role, row['snapshot']), 'Historical input snapshot must remain exact')
        for field in ('build_outputs', 'variant_sources'):
            for path, digest in report.get(field, {}).items():
                need(identity(role, path) == digest, 'Actual build/variant identity differs')
        for path, digest in report.get('tools', {}).items():
            need(manifest['external_omitted'][norm(path)]['raw_sha256'] == digest, 'Actual tool/archive omission identity')
        if role == 'numeric':
            continue
        need((report['platform'], report['sdk_revision'], report['elf_machine'], report['coordinator_core'], report['worker_core']) ==
             ('esp32c3', SDK, 243, 0, 0), 'C3 target profile differs')
        need([row['name'] for row in report['commands']] == (COMMANDS[:7] if role == 'baseline' else COMMANDS), 'Actual owned command inventory differs')
        for command in report['commands']:
            need(command['state'] == 'complete' and type(command['exit_status']) is int and command['exit_status'] == 0 and
                 command['timed_out'] is False and command['interrupted'] is False and type(command['pid']) is int and
                 command['pid'] > 0 and command['argv'] and command['cwd'], 'Actual child terminal facts required')
            for stream in ('stdout', 'stderr'):
                need(identity(role, command['name'] + '.' + stream + '.log') == command[stream + '_sha256'], 'Actual child log identity')
        need(identity(role, 'sources/helpers/run.py') == RUNNER and identity(role, 'sources/helpers/protocol.py') == PROTOCOL, 'Reviewed C3 runtime sources required')
        need(report['selected_setup_sha256'] == identity(role, 'variant/vorbis_repair/setup.c') ==
             identity(role, 'sources/candidate/vorbis_repair/setup.c') == (OLD if role == 'baseline' else FIXED), 'Actual selected C3 setup binding')
        context = report['setup_macro_context']
        need(context['row'] in record(role, 'build/compile_commands.json'), 'Actual setup compile row missing')
        generated = context['generated_inputs']
        need(len(generated) == 2, 'Exact actual four-line cflags/specs context required')
        for path, row in generated.items():
            need(row['sha256_before'] == row['sha256_after'] == files[original(role, path)]['raw_sha256'], 'Generated macro inputs changed')
        flags = next(path for path in generated if norm(path).endswith('/toolchain/cflags'))
        specs = next(path for path in generated if norm(path).endswith('/specs/picolibc.specs'))
        need(raw[original(role, flags)].decode().splitlines() == ['-march=rv32imc_zicsr_zifencei', '-mtune=esp-base',
             '"-specs=' + norm(specs) + '"', '-D__PICOLIBC_ERRNO_FUNCTION=__errno'], 'Actual RV32 response file differs')
        macros = data(role, 'setup-macros.stdout.log').decode().replace('\r\n', '\n')
        for name, value in (('CONFIG_ESP_DEFAULT_CPU_FREQ_MHZ', 160), ('CONFIG_FREERTOS_UNICORE', 1),
                            ('__riscv_xlen', 32), ('__SIZEOF_LONG__', 4), ('__SIZEOF_POINTER__', 4),
                            ('CONFIG_IDF_TARGET_ESP32C3', 1), ('ESP_PLATFORM', 1)):
            need(re.search('^#define ' + name + ' ' + str(value) + '$', macros, re.M), 'Actual C3 compile macro differs')
        need(not re.search(r'^#define LIMIT_TO_64kHz\b', macros, re.M) and
             data(role, 'sdk-head.stdout.log').strip().decode() == SDK and not data(role, 'sdk-clean.stdout.log').strip(), 'Actual SDK/config proof differs')
        need(any(k.startswith(key(role, 'build/')) and 'actual_elf_header64_hex' in row for k, row in files.items()), 'Actual C3 ELF64 metadata missing')
        need(any(k.startswith(key(role, 'build/')) and k.endswith('.map') for k in raw), 'Actual link map missing')

    def events(role):
        log = (data(role, 'qemu.stdout.log') + b'\n' + data(role, 'qemu.stderr.log')).decode(errors='replace')
        need(not re.search(PANIC, log, re.I), 'Unexpected target panic/watchdog')
        return log, [line for line in log.splitlines() if line.startswith(PREFIX)]

    accepted = reports['acceptance']
    need(accepted['result'] == 'CHECKED_CORPUS_PCM_CAPTURED' and accepted['completed'] is True and
         accepted['target_capture_completed'] is True and accepted['checked_decode_completed'] is True, 'Actual acceptance capture incomplete')
    contract = record('acceptance', 'sources/corpus/contract.json')
    need(identity('acceptance', 'sources/corpus/contract.json') == '717ec7f703295f9851fd9241877cf249ff6f203c436786300a36247f2805218d' and
         contract['contract_sha256'] == '660ac01523d3336ccb103f1443e51b870edf1a3d3f50321c5666969b1da634cc', 'Exact reviewed25 model required')
    protocol_path = bundle / files[key('acceptance', 'sources/helpers/protocol.py')]['stored']
    protocol = module_from_path('archived_c3_checked25_protocol', protocol_path, PROTOCOL)
    class ArchivedOriginalPath(PureWindowsPath):
        def resolve(self): return type(self)(ntpath.normpath(str(self)))
        def read_bytes(self): return raw[original('acceptance', self.resolve())]
    protocol.Path = ArchivedOriginalPath
    qemu = accepted['commands'][6]
    log, accepted_events = events('acceptance')
    observed = protocol.validate_log(log, contract, returncode=qemu['exit_status'], timed_out=qemu['timed_out'],
        interrupted=qemu['interrupted'], manifest_hashes=contract['model']['manifest_sha256'])
    captured = observed.pop('case_pcm')
    need(observed == accepted['observed'] and (observed['cases'], observed['decoded_packets'], observed['pcm'], observed['protocol_lines']) ==
         (25, 350, 623360, 778), 'Strict actual full25 protocol differs')
    need(len(captured) == len(accepted['observed_pcm']) == 25, 'Actual persisted25 accounting differs')
    for item, row in zip(captured, accepted['observed_pcm']):
        need(item['case'] == row['case'] and item['id'] == row['id'] and item['packet_offsets'] == row['packet_offsets'] and
             item['sha256'] == row['sha256'] and item['pcm'] == data('acceptance', row['path']), 'Actual PCM persistence differs')
    need({key('acceptance', row['path']) for row in accepted['observed_pcm']} ==
         {k for k in raw if k.startswith(key('acceptance', 'observed-pcm/'))}, 'Actual25 PCM inventory differs')
    baseline = reports['baseline']
    need(baseline['result'] == 'NONPASS' and baseline['completed'] is False and baseline['target_capture_completed'] is False,
         'Actual baseline NONPASS lost')
    _, got = events('baseline')
    begin = next(i for i, line in enumerate(accepted_events) if line.startswith(PREFIX + 'OPEN case=6 '))
    need(begin == 188 and got[:begin] == accepted_events[:begin] and got[begin:] == [
        PREFIX + 'OPEN case=6 id=sparse_explicit_d4_seq0 checked_rc=-1 checked_handle=0 core=0',
        PREFIX + 'FAILURE case=6 packet=0 reason=checked_public_open core=0'], 'Exact baseline/fixed prefix causality differs')
    need(data('baseline', 'sources/corpus/contract.json') == data('acceptance', 'sources/corpus/contract.json'), 'Baseline/fixed contract differs')
    relation_root = '.build/c3-vorbis-map2-root-source-01/'
    source_relation = obj(raw[relation_root + 'relation.json'])
    need(sha(raw[relation_root + 'before.c']) == OLD and sha(raw[relation_root + 'after.c']) == FIXED and
         source_relation['before_sha256'] == OLD and source_relation['after_sha256'] == FIXED and
         source_relation['outside_reviewed_functions_unchanged'] is True and source_relation['CRLF_preserved'] is True, 'Root source relation differs')
    witness = obj(raw['.build/c3-vorbis-map2-before-after-witness-01.json'])
    need(witness['baseline_report_sha256'] == identity('baseline', 'report.json') and witness['fixed_report_sha256'] == identity('acceptance', 'report.json') and
         witness['expected_prior_failure_observed'] is True and witness['prerequisite_prefix_byte_equal'] is True and
         (witness['completed_prerequisite_cases'], witness['completed_prerequisite_packets'], witness['completed_prerequisite_pcm_bytes']) ==
         (6, 84, 168960) and witness['PCM_qualification'] is False, 'Root before/after witness differs')

    measured = reports['numeric']
    need(measured['result'] == 'BOUNDED_CORPUS_PCM_REJECTED' and measured['measurement_completed'] is True and
         measured['actual_reference_compared'] is True and measured['target_platform_verified'] is True and
         measured['bounded_corpus_pcm_qualified'] is False and len(measured['cases']) == 25, 'Actual full25 numeric NONPASS lost')
    platform = measured['target_platform']
    need((platform['platform'], platform['sdk_revision'], platform['elf_machine'], platform['coordinator_core'],
          platform['worker_core'], platform['selected_setup_sha256'], platform['assumed_CYD_binary_equivalence']) ==
         ('esp32c3', SDK, 243, 0, 0, FIXED, False), 'Actual numeric C3 source/platform facts differ')
    numeric_root = '.build/c3-vorbis-format-expanded25-numeric-prep-02/'
    metrics_path = bundle / files[numeric_root + 'pcm_metrics.py']['stored']
    metrics = module_from_path('pcm_metrics', metrics_path, METRICS)
    old_module = sys.modules.get('pcm_metrics')
    sys.modules['pcm_metrics'] = metrics
    try:
        policy = module_from_path('archived_c3_policy25', bundle / files[numeric_root + 'policy25.py']['stored'], POLICY)
    finally:
        if old_module is None: sys.modules.pop('pcm_metrics', None)
        else: sys.modules['pcm_metrics'] = old_module
    binding = record('acceptance', 'sources/reference/reference-binding02.json')
    need(identity('acceptance', 'sources/reference/reference-binding02.json') == '802d0fe193991cfc40d388ad27594d8d0b632112f223cb6dee68226c07585f2c', 'Original17/new8 binding differs')
    target_books, reference_books, maxima = {}, {}, []
    for index, (case, pcm, result, bound) in enumerate(zip(contract['model']['cases'], captured, measured['cases'], binding['cases'])):
        host_role = 'host-new8' if bound['original_group'] == 'newbooks8' else 'host-old17'
        host = reports[host_role]
        hostcase = next(row for row in host['cases'] if row['id'] == bound['original_reference_id'])
        wav_bytes = data(host_role, f"cases/{hostcase['id']}/libvorbis.wav")
        declared = hostcase['decoded']['libvorbis']
        need(sha(wav_bytes) == declared['wav_sha256'], 'Actual independent WAV identity differs')
        with wave.open(io.BytesIO(wav_bytes), 'rb') as wav:
            need((wav.getnchannels(), wav.getsampwidth(), wav.getframerate(), wav.getnframes()) ==
                 (2, 2, case['rate'], sum(case['frames'])), 'Actual independent WAV format/count differs')
            reference = wav.readframes(wav.getnframes())
        need(sha(reference) == declared['pcm_sha256'] == bound['reference_pcm_sha256'] and
             len(reference) == len(pcm['pcm']) == case['total_pcm'] and bound['id'] == case['id'] and
             bound['raw_sha256'] == case['raw_sha256'], 'Raw/reference/target binding differs')
        for kind in ('identification', 'setup', 'audio'):
            path = PureWindowsPath(hostcase['source_matrix']).parent / hostcase['input'][kind]
            need(sha(raw[original(host_role, path)]) == case['raw_sha256'][kind], 'Actual independent raw packet identity differs')
        need(result['case'] == index and result['id'] == case['id'] and result['comparison'] == metrics.compare(reference, pcm['pcm'], case['pcm']) and
             result['alignment'] == metrics.alignment(reference, pcm['pcm'], 8) and result['packet_offsets'] == pcm['packet_offsets'], 'All actual signed-S16 packet/channel/diagnostic metrics differ')
        for label, value in (('reference_transition_channel_nonzero', reference), ('target_transition_channel_nonzero', pcm['pcm'])):
            counts = {name: [0, 0] for name in ('SS', 'SL', 'LS', 'LL')}
            for packet in range(1, 14):
                name = 'SL'[case['modes'][packet-1]] + 'SL'[case['modes'][packet]]
                first, stop = pcm['packet_offsets'][packet:packet+2]
                for channel in (0, 1):
                    counts[name][channel] += sum(value[i:i+2] != b'\x00\x00' for i in range(first + channel*2, stop, 4))
            need(result[label] == counts, 'Actual transition/channel nonzero counts differ')
        maxima.append(result['comparison']['zero_lag_direct_LR']['max_abs_error'])
        if index < 16:
            target_books[case['id']], reference_books[case['id']] = pcm['pcm'], reference
    declarations = [dict(decoder='libvorbis', kind=row['kind'], cases=row['cases'], passed=True)
                    for row in measured['metamorphic_relations']['xiph']]
    cyd_numeric_root = dep.manifest['roles']['numeric-expanded25']['root']
    historical_numeric = obj(dep.read(cyd_numeric_root + '/report.json'))
    need(measured['metamorphic_relations']['xiph'] == historical_numeric['metamorphic_relations']['xiph'] and
         measured['source_reference_scopes'] == binding['source_scopes'], 'Actual independently declared old17/new8 Xiph relations changed')
    relations = dict(xiph=policy.relations8(reference_books, declarations), target=policy.relations8(target_books, declarations))
    need(relations == measured['metamorphic_relations'], 'Actual eight relations per decoder differ')
    full_policy, full_ok = policy.bounded_policy25(measured['cases'], relations, 2)
    sub_policy, sub_ok = policy.bounded_policy_books16(measured['cases'][:16], relations, 2)
    subgroup = measured['declared_subgroup_books16']
    need(full_policy == measured['policy'] and full_ok is measured['bounded_corpus_pcm_qualified'] is False and
         sub_policy == subgroup['policy'] and sub_ok is subgroup['bounded_subgroup_pcm_qualified'] is False and
         subgroup['case_indices'] == list(range(16)) and subgroup['does_not_override_full25'] is True, 'Preserved fixed-bound full25/books16 policies differ')
    cross = obj(raw['.build/c3-cyd-vorbis-expanded25-output-relation-01.json'])
    cyd_role = dep.manifest['roles']['capture25']['root']
    cyd_report = obj(dep.read(cyd_role + '/report.json'))
    need(len(cross['cases']) == 25 and cross['all_actual_bytes_equal'] is False and cross['numerical_reference_qualified'] is False, 'Cross-architecture scope differs')
    unequal = []
    for index, (item, c3, cyd) in enumerate(zip(cross['cases'], captured, cyd_report['observed_pcm'])):
        cyd_pcm = dep.read(cyd_role + '/' + norm(cyd['path']))
        equal = c3['pcm'] == cyd_pcm
        need(item == dict(case=index, id=c3['id'], C3_sha256=sha(c3['pcm']), CYD_sha256=sha(cyd_pcm), actual_PCM_byte_equal=equal), 'Actual cross-architecture bytes differ from root evidence')
        if not equal: unequal.append(index)
    need(unequal == [8, 9, 10, 11], 'Preserved cross-architecture wide differences changed')
    dep.current()
    return dict(verified=True, cases=25, packets=350, pcm_bytes=623360, baseline_NONPASS_preserved=True,
        numeric_NONPASS_preserved=True, max_abs_errors=maxima, full25_bounded=False, books16_bounded=False,
        cross_architecture_equal_cases=21, cross_architecture_unequal_case_indices=unequal,
        format_conformance_qualified=False, full_G6_qualified=False, physical_device=False, production_firmware=False)


