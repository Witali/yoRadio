"""Test unpublished startup storage against the real adaptive queue with host RTOS stubs."""
import argparse
import hashlib
import json
from pathlib import Path
import sys
from native_source import source_closure

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools/codec_benchmark'))
from run_output_dma_host import host, run
sys.path.insert(0, str(ROOT / 'tests'))
import importlib.util
spec = importlib.util.spec_from_file_location('queue_runner', ROOT/'tests/run-adaptive-input.py')
queue_runner = importlib.util.module_from_spec(spec)
spec.loader.exec_module(queue_runner)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--corpus', type=Path, help='Input directory generated by run-stream-confirm.py')
    args = parser.parse_args()
    out = args.output.resolve()
    out.mkdir(parents=True, exist_ok=False)
    source = ROOT/'idf/esp32c3-oled-native/main'
    platform = ROOT/'tests/native/adaptive_input_test.c'
    test = ROOT/'tests/native/stream_staging_test.c'
    prelude = platform.read_text().split('#define MALLOC_CAP_INTERNAL')[0]
    prelude = prelude.replace('/* PRODUCTION_HEADER */', queue_runner.body(source/'adaptive_input.h'))
    prelude = prelude.replace('/* PRODUCTION_QUEUE */', queue_runner.body(source/'adaptive_input.c'))
    unit = out/'test.c'
    unit.write_text(prelude + test.read_text().replace('/* STAGING_HEADER */',
                                                      queue_runner.body(source/'stream_staging.h')))
    binary = out/'test'
    (out/'build.log').write_bytes(run(['gcc', '-std=c11', '-O2', '-g', '-Wall', '-Wextra', '-Werror',
        '-pthread', '-fsanitize=address,undefined', '-fno-pie', '-no-pie',
        '-I', host(source), host(unit), '-o', host(binary)]))
    try:
        log = run(['env', 'ASAN_OPTIONS=detect_leaks=1:halt_on_error=1',
                   'UBSAN_OPTIONS=halt_on_error=1', host(binary)])
    except Exception as error:
        if hasattr(error, 'output'):
            (out/'failure.log').write_bytes(error.output)
            print(error.output.decode())
        raise
    (out/'run.log').write_bytes(log)
    assert log.startswith(b'PASS staging:')
    cases = []
    if args.corpus:
        original = json.loads((args.corpus/'report.json').read_text())
        assert original['passed']
        for case in original['cases']:
            path = args.corpus/(case['name']+'.input')
            assert hashlib.sha256(path.read_bytes()).hexdigest()==case['sha256']
            result = run([host(binary),host(path)])
            expected = (args.corpus/(case['name']+'.log')).read_bytes()
            # The prior core harness has a unit-test line before the results.
            expected = b'\n'.join(x for x in expected.splitlines() if x.startswith(b'READY '))+b'\n'
            assert result==expected,case['name']
            (out/(case['name']+'.log')).write_bytes(result)
            cases.append(case)
    sources = [Path(__file__).resolve(), ROOT/'tests/run-adaptive-input.py', platform, test] + [source/name
        for name in ('adaptive_input.h', 'adaptive_input.c', 'stream_staging.h', 'stream_confirm.h',
                     'stream_probe.h', 'stream_frames.h', 'stream_tags.h')]
    hashes = {}
    sources = source_closure(sources)
    for path in sources:
        relative = path.relative_to(ROOT)
        target = out/'sources'/relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(path.read_bytes())
        hashes[relative.as_posix()] = hashlib.sha256(path.read_bytes()).hexdigest()
    (out/'report.json').write_text(json.dumps(dict(passed=True, sources=hashes,
        random_operations=20000, corpus=cases, scope=__doc__, firmware_integration=False), indent=2)+'\n')
    print(log.decode(), end='')
    print(f'PASS actual-queue corpus: {len(cases)} cases with 1/7/2048-byte chunks')


if __name__ == '__main__':
    main()
