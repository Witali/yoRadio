"""Generate exact immutable 12-bit lookup tables from pinned IJG arithmetic."""
import argparse
from decimal import Decimal
import difflib
from pathlib import Path
import subprocess

from build import PIN


def array_header(kind, name, values):
    """Emit deterministic C literals; no initializer or heap allocation runs at boot."""
    lines = [f"static const {kind} {name}[{len(values)}] = {{\n"]
    for offset in range(0, len(values), 8):
        lines.append("  " + ", ".join(str(value) for value in values[offset:offset + 8]) + ",\n")
    return "".join(lines) + "};\n"


def header_notice():
    """Retain the provenance and IJG attribution for the derived initialization data."""
    return ("/* Generated by Small TV generate_flash_tables.py; do not edit.\n"
            " * Copyright (C) 2026 Small TV contributors.\n"
            " * Values reproduce libjpeg-turbo 3.2.0 jdmaster.c/jdcolor.c tables.\n"
            " * This software is based in part on the work of the Independent JPEG Group.\n"
            " * For conditions of distribution and use, see README.ijg. */\n\n")


def range_values():
    """Reproduce all segments, including masked-IDCT wraparound and negative indices."""
    count, center = 4096, 2048
    values = [0] * (5 * count + center)
    values[count:2 * count] = range(count)
    post = count + center
    values[post + center:post + 2 * count] = [count - 1] * (2 * count - center)
    values[post + 4 * count - center:post + 4 * count] = range(center)
    assert len(values) == 22528
    return values


def fixed(text):
    """Match positive FIX constants exactly without depending on Python binary floats."""
    return int(Decimal(text) * 65536 + Decimal("0.5"))


def color_values():
    """Preserve upstream's individual rounding and combined green-channel rounding."""
    samples = range(-2048, 2048)
    return {
        "cr_r": [(fixed("1.40200") * value + 32768) >> 16 for value in samples],
        "cb_b": [(fixed("1.77200") * value + 32768) >> 16 for value in samples],
        "cr_g": [-fixed("0.71414") * value for value in samples],
        "cb_g": [-fixed("0.34414") * value + 32768 for value in samples],
    }


def replace_once(text, old, new):
    """Refuse a changed upstream layout instead of silently generating a partial patch."""
    if text.count(old) != 1:
        raise ValueError(f"Expected exactly one source anchor: {old[:80]!r}")
    return text.replace(old, new, 1)


def main():
    """Generate a supplemental patch; the bounded patch remains a separate input."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    actual = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=args.source, text=True).strip()
    if actual != PIN:
        raise ValueError(f"Expected upstream {PIN}, got {actual}")

    def committed(name):
        """Read Git object bytes, unaffected by checkout EOL or generated wrappers."""
        return subprocess.check_output(["git", "show", f"{PIN}:src/{name}"], cwd=args.source).decode()

    old_master = committed("jdmaster.c")
    master = replace_once(old_master, '#include "jdmaster.h"',
                          '#include "jdmaster.h"\n#include "small_tv_jpeg12_range.h"')
    master = replace_once(master, "  J12SAMPLE *table12;\n", "")
    master = replace_once(master, "prepare_range_limit_table(j_decompress_ptr cinfo)\n/* Allocate and fill in the sample_range_limit table */\n{",
                         "prepare_range_limit_table(j_decompress_ptr cinfo)\n/* Allocate and fill in the sample_range_limit table */\n{\n"
                         "  /* REQUESTED_CHANGE: keep the exact 12-bit lookup in read-only flash.\n"
                         "   * Its legacy public pointer is mutable, but all consumers only read. */")
    start = master.index("  } else if (cinfo->data_precision <= 12) {")
    end = master.index("  } else {\n#ifdef D_LOSSLESS_SUPPORTED\n    table16", start)
    assert start > master.index("prepare_range_limit_table(j_decompress_ptr cinfo)")
    assert "table12 = (J12SAMPLE *)" in master[start:end]
    assert "memcpy(table12 + (4 * (MAXJ12SAMPLE + 1) - CENTERJ12SAMPLE)," in master[start:end]
    master = master[:start] + (
        "  } else if (cinfo->data_precision <= 12) {\n"
        "    cinfo->sample_range_limit = (JSAMPLE *)(small_tv_jpeg12_range +\n"
        "                                           (MAXJ12SAMPLE + 1));\n") + master[end:]
    old_color = committed("jdcolor.c")
    color = replace_once(old_color, " * For conditions of distribution and use,",
                         " * Small TV modifications: Copyright (C) 2026 Small TV contributors.\n"
                         " * For conditions of distribution and use,")
    color = replace_once(color, '#include "jsamplecomp.h"', '#include "jsamplecomp.h"\n'
                         '#if BITS_IN_JSAMPLE == 12\n#include "small_tv_jpeg12_color.h"\n#endif')
    color = replace_once(color, "build_ycc_rgb_table(j_decompress_ptr cinfo)\n{\n#if BITS_IN_JSAMPLE != 16",
                         "build_ycc_rgb_table(j_decompress_ptr cinfo)\n{\n"
                         "  /* REQUESTED_CHANGE: reuse immutable 12-bit color lookups in flash.\n"
                         "   * Retain upstream rounding and lookup types; no color algorithm changes. */\n"
                         "#if BITS_IN_JSAMPLE == 12\n"
                         "  my_cconvert_ptr cconvert = (my_cconvert_ptr)cinfo->cconvert;\n"
                         "  /* Only this initializer writes these legacy pointer fields. */\n"
                         "  cconvert->Cr_r_tab = (int *)small_tv_jpeg12_cr_r;\n"
                         "  cconvert->Cb_b_tab = (int *)small_tv_jpeg12_cb_b;\n"
                         "  cconvert->Cr_g_tab = (JLONG *)small_tv_jpeg12_cr_g;\n"
                         "  cconvert->Cb_g_tab = (JLONG *)small_tv_jpeg12_cb_g;\n"
                         "#elif BITS_IN_JSAMPLE != 16")
    range_header = header_notice() + array_header("J12SAMPLE", "small_tv_jpeg12_range", range_values())
    colors = color_values()
    color_header = header_notice() + "\n".join(array_header("int" if key in ("cr_r", "cb_b") else "JLONG",
                                                             "small_tv_jpeg12_" + key, values)
                                                     for key, values in colors.items())
    patch = []
    for name, old, new in (("jdmaster.c", old_master, master), ("jdcolor.c", old_color, color),
                            ("small_tv_jpeg12_range.h", "", range_header),
                            ("small_tv_jpeg12_color.h", "", color_header)):
        if not old:
            patch.append(f"diff --git a/src/{name} b/src/{name}\nnew file mode 100644\n")
        patch.extend(difflib.unified_diff(old.splitlines(True), new.splitlines(True),
                                         fromfile="a/src/" + name if old else "/dev/null", tofile="b/src/" + name))
    args.output.write_text("".join(patch), encoding="utf-8", newline="\n")
    print("Generated 22528 range entries and 4×4096 color entries; 110592 read-only bytes.")


if __name__ == "__main__":
    main()
