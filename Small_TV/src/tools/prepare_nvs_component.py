"""Generate a source-qualified local NVS component with consistent recovery declarations."""
import argparse
import json
from pathlib import Path
import re

from patch_nvs_page import patch as patch_page, FIXES as PAGE_FIXES, sha, write_changed

HERE = Path(__file__).resolve().parent
FRAGMENTS = HERE.parent/'storage/nvs'
REPLACEMENTS = {
 'nvs_pagemanager.cpp': {'esp_err_t PageManager::load(': 'page_manager_load.inc'},
 'nvs_storage.cpp': {'esp_err_t Storage::populateBlobIndices(': 'populate_blob_indices.inc',
                     'void Storage::eraseMismatchedBlobIndexes(': 'erase_mismatched_indices.inc',
                     'void Storage::eraseOrphanDataBlobs(': 'erase_orphan_blobs.inc',
                     'esp_err_t Storage::init(': 'storage_init.inc'},
}


def sources(component):
    """Reject changed or added vendor code before generating any compilation input."""
    manifest = json.loads((HERE/'nvs_component_sources.json').read_bytes())
    expected_fragments = {name for replacements in REPLACEMENTS.values() for name in replacements.values()}
    if {p.name for p in FRAGMENTS.glob('*.inc')} != expected_fragments:
        raise ValueError('NVS correction fragment inventory changed')
    if manifest['schema'] != 'small-tv-nvs-component-sources-v1': raise ValueError('Wrong NVS source manifest')
    paths = {p.relative_to(component).as_posix(): p for folder in ('src', 'include', 'private_include')
             for p in (component/folder).rglob('*') if p.is_file() and p.suffix in ('.c', '.cpp', '.h', '.hpp')}
    if set(paths) != set(manifest['files']): raise ValueError('NVS component source inventory changed')
    raw = {name: path.read_bytes() for name, path in paths.items()}
    if any(sha(value) != manifest['files'][name] for name, value in raw.items()):
        raise ValueError('NVS component source bytes changed; requalify the SDK')
    result = {name.removeprefix('src/'): value for name, value in raw.items() if name.startswith('src/')}
    if any('/' in name for name in result): raise ValueError('Requalify nested NVS source directory')
    result['nvs_page.cpp'] = patch_page(result['nvs_page.cpp'])
    for name, functions in REPLACEMENTS.items():
        text = result[name].decode('utf8').replace('\r\n', '\n')
        for signature, filename in functions.items():
            if text.count(signature) != 1: raise ValueError('Missing/ambiguous NVS recovery definition')
            begin = text.index(signature); end = re.search(r'(?m)^}', text[begin:])
            if end is None: raise ValueError('Unterminated NVS recovery definition')
            replacement = (FRAGMENTS/filename).read_text(encoding='utf8').replace('\r\n', '\n').rstrip()
            text = text[:begin]+replacement+text[begin+end.end():]
        result[name] = text.encode('utf8')
    header = result['nvs_storage.hpp'].decode('utf8').replace('\r\n', '\n')
    for name in ('eraseMismatchedBlobIndexes', 'eraseOrphanDataBlobs'):
        declaration = 'void '+name+'(TBlobIndexList&);'
        if header.count(declaration) != 1: raise ValueError('NVS private cleanup declaration changed')
        header = header.replace(declaration, 'esp_err_t '+name+'(TBlobIndexList&);')
    result['nvs_storage.hpp'] = header.encode('utf8')
    return result, raw


def report(generated, raw):
    """Identify every checked vendor byte, generated byte and local correction fragment."""
    return dict(schema='small-tv-nvs-storage-overlay-v1',
                source_manifest_sha256=sha((HERE/'nvs_component_sources.json').read_bytes()),
                generator_sha256=sha(Path(__file__).read_bytes()), page_generator_sha256=sha((HERE/'patch_nvs_page.py').read_bytes()),
                sources={k: sha(v) for k, v in sorted(raw.items())}, generated={k: sha(v) for k, v in sorted(generated.items())},
                fragments={p.name: sha(p.read_bytes()) for p in sorted(FRAGMENTS.glob('*.inc'))},
                fixes=['page-manager-error-propagation', 'storage-error-propagation', 'temporary-index-scope-cleanup'],
                shared_sdk_modified=False)


def main():
    """Copy all component TUs/headers locally so private return-type changes obey the C++ ODR."""
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ('component', 'output', 'reports'): parser.add_argument('--'+name, type=Path, required=True)
    args = parser.parse_args(); component, output = args.component.resolve(), args.output.resolve()
    reports = args.reports.resolve()
    if output.is_relative_to(component) or component.is_relative_to(output):
        raise ValueError('NVS overlay must stay outside the shared SDK')
    if reports.is_relative_to(component) or reports == output:
        raise ValueError('NVS reports must stay outside the shared SDK and source overlay')
    generated, original = sources(component)
    if output.exists() and set(p.name for p in output.iterdir())-set(generated):
        raise ValueError('Preserve unknown files in NVS overlay directory')
    for name, value in generated.items(): write_changed(output/name, value)
    page_report = dict(schema='small-tv-nvs-recovery-v1', source_sha256=sha(original['src/nvs_page.cpp']),
                       generated_sha256=sha(generated['nvs_page.cpp']), generator_sha256=sha((HERE/'patch_nvs_page.py').read_bytes()),
                       fixes=list(PAGE_FIXES), shared_sdk_modified=False)
    write_changed(args.reports/'nvs-recovery.json', (json.dumps(page_report, indent=2)+'\n').encode())
    value = report(generated, original)
    write_changed(args.reports/'nvs-storage-overlay.json', (json.dumps(value, indent=2)+'\n').encode())
    print(json.dumps(dict(passed=True, checked_files=len(original), generated_files=len(generated))))


if __name__ == '__main__': main()
